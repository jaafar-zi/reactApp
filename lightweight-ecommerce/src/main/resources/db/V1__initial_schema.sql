-- =====================================================================
-- 1. PRODUCTS
-- =====================================================================

CREATE TABLE products (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku              VARCHAR(255) NOT NULL UNIQUE,
    name_key         VARCHAR(255) NOT NULL,
    description_key  VARCHAR(255),
    active           BOOLEAN NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMP,
    updated_at       TIMESTAMP
);


-- =====================================================================
-- 2. PRODUCT VARIANTS
-- =====================================================================

CREATE TABLE product_variants (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   BIGINT NOT NULL,
    sku          VARCHAR(255) NOT NULL UNIQUE,
    size         VARCHAR(10) NOT NULL,
    active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMP,
    updated_at   TIMESTAMP,
    CONSTRAINT fk_variant_product
        FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE
);


-- =====================================================================
-- 3. PRODUCT PRICING
-- =====================================================================

CREATE TABLE product_pricing (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   BIGINT NOT NULL,
    base_price   NUMERIC(10, 2) NOT NULL,
    sale_price   NUMERIC(10, 2),
    currency     VARCHAR(3) NOT NULL DEFAULT 'USD',
    tax_rate     NUMERIC(5, 2) DEFAULT 0,
    CONSTRAINT fk_pricing_product
        FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE
);


-- =====================================================================
-- 4. INVENTORY
-- =====================================================================
-- Either product_id OR variant_id is set, never both.
-- Products without variants  → product_id is set, variant_id is NULL
-- Products with variants     → variant_id is set, product_id is NULL

CREATE TABLE inventory (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id        BIGINT,
    variant_id        BIGINT,
    quantity          INTEGER NOT NULL DEFAULT 0,
    reserved_quantity INTEGER NOT NULL DEFAULT 0,
    min_stock_level   INTEGER NOT NULL DEFAULT 5,
    last_updated      TIMESTAMP,
    CONSTRAINT fk_inventory_product
        FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT fk_inventory_variant
        FOREIGN KEY (variant_id) REFERENCES product_variants (id) ON DELETE CASCADE,
    CONSTRAINT uq_inventory_product UNIQUE (product_id),
    CONSTRAINT uq_inventory_variant UNIQUE (variant_id),
    CONSTRAINT chk_inventory_owner
        CHECK (
            (product_id IS NOT NULL AND variant_id IS NULL)
            OR (product_id IS NULL AND variant_id IS NOT NULL)
        )
);


-- =====================================================================
-- 5. PRODUCT ATTRIBUTES
-- =====================================================================

CREATE TABLE product_attributes (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id     BIGINT NOT NULL,
    attribute_key  VARCHAR(255) NOT NULL,
    language       VARCHAR(255) NOT NULL,
    CONSTRAINT fk_attr_product
        FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE
);


-- =====================================================================
-- 6. ATTRIBUTE VALUES
-- =====================================================================
-- NOTE: product_attribute_id is TEXT per entity columnDefinition.
--       FK constraint omitted due to type mismatch with BIGINT PK.

CREATE TABLE attribute_values (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_attribute_id   TEXT NOT NULL,
    value                  VARCHAR(255) NOT NULL
);


-- =====================================================================
-- 7. ATTRIBUTE KEY TRANSLATIONS
-- =====================================================================
-- Translates attribute_key labels for the UI.
-- e.g. 'product_details' → 'Product Details' (en)
--                         → 'Détails du produit' (fr)
--                         → 'تفاصيل المنتج' (ar)

CREATE TABLE attribute_key_translations (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attribute_key  VARCHAR(255) NOT NULL,
    language       VARCHAR(10) NOT NULL,
    label          VARCHAR(255) NOT NULL,
    CONSTRAINT uq_attr_key_lang UNIQUE (attribute_key, language)
);


-- =====================================================================
-- 8. PRODUCT ASSETS
-- =====================================================================

CREATE TABLE product_assets (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id     BIGINT NOT NULL,
    asset_type     VARCHAR(255) NOT NULL,
    url            VARCHAR(255) NOT NULL,
    alt_text       VARCHAR(255),
    display_order  INTEGER NOT NULL DEFAULT 0,
    is_primary     BOOLEAN DEFAULT FALSE,
    CONSTRAINT fk_asset_product
        FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE
);


-- =====================================================================
-- 9. ADDRESSES
-- =====================================================================

CREATE TABLE addresses (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name       VARCHAR(255) NOT NULL,
    phone_number    VARCHAR(255) NOT NULL,
    address_line1   VARCHAR(255) NOT NULL,
    address_line2   VARCHAR(255),
    city            VARCHAR(255) NOT NULL,
    state           VARCHAR(255) NOT NULL,
    postal_code     VARCHAR(255) NOT NULL,
    country         VARCHAR(255) NOT NULL,
    type            VARCHAR(255) NOT NULL,
    is_default      BOOLEAN NOT NULL DEFAULT FALSE,
    customer_email  VARCHAR(255),
    notes           TEXT,
    created_at      TIMESTAMP,
    updated_at      TIMESTAMP
);


-- =====================================================================
-- 10. DISCOUNT CODES
-- =====================================================================

CREATE TABLE discount_codes (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                   VARCHAR(100) NOT NULL UNIQUE,
    user_prefix            VARCHAR(30) NOT NULL,
    discount_type          VARCHAR(20) NOT NULL,
    discount_value         NUMERIC(10, 2) NOT NULL,
    minimum_order_amount   NUMERIC(10, 2),
    max_uses               INTEGER,
    current_uses           INTEGER NOT NULL DEFAULT 0,
    max_uses_per_customer  INTEGER,
    expires_at             TIMESTAMP,
    active                 BOOLEAN NOT NULL DEFAULT TRUE,
    created_at             TIMESTAMP,
    updated_at             TIMESTAMP
);


-- =====================================================================
-- 11. ORDERS
-- =====================================================================

CREATE TABLE orders (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number           VARCHAR(255) NOT NULL UNIQUE,
    customer_phone         VARCHAR(20) NOT NULL,
    customer_email         VARCHAR(255),
    customer_name          VARCHAR(255) NOT NULL,
    status                 VARCHAR(255) NOT NULL DEFAULT 'CONFIRMED',
    discount_code_id       BIGINT,
    applied_discount_code  VARCHAR(100),
    discount_amount        NUMERIC(10, 2) NOT NULL DEFAULT 0,
    subtotal               NUMERIC(10, 2) NOT NULL,
    shipping_cost          NUMERIC(10, 2) NOT NULL DEFAULT 0,
    tax                    NUMERIC(10, 2) NOT NULL,
    total                  NUMERIC(10, 2) NOT NULL,
    currency               VARCHAR(3) DEFAULT 'TND',
    shipping_address       VARCHAR(255),
    billing_address        VARCHAR(255),
    created_at             TIMESTAMP,
    updated_at             TIMESTAMP,
    CONSTRAINT fk_order_discount
        FOREIGN KEY (discount_code_id) REFERENCES discount_codes (id) ON DELETE SET NULL
);


-- =====================================================================
-- 12. ORDER ITEMS
-- =====================================================================

CREATE TABLE order_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT NOT NULL,
    product_id   BIGINT NOT NULL,
    variant_id   BIGINT,
    quantity     INTEGER NOT NULL,
    unit_price   NUMERIC(10, 2) NOT NULL,
    total_price  NUMERIC(10, 2) NOT NULL,
    CONSTRAINT fk_item_order
        FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_item_product
        FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT fk_item_variant
        FOREIGN KEY (variant_id) REFERENCES product_variants (id) ON DELETE SET NULL
);


-- =====================================================================
-- 13. SHIPPINGS
-- =====================================================================

CREATE TABLE shippings (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tracking_number          VARCHAR(255) NOT NULL UNIQUE,
    order_id                 BIGINT NOT NULL UNIQUE,
    shipping_address_id      BIGINT NOT NULL,
    shipping_method          VARCHAR(255) NOT NULL,
    current_status           VARCHAR(255) NOT NULL,
    carrier                  VARCHAR(255) NOT NULL,
    shipping_cost            NUMERIC(10, 2),
    weight                   NUMERIC(5, 2),
    estimated_delivery_date  TIMESTAMP,
    actual_delivery_date     TIMESTAMP,
    shipped_date             TIMESTAMP,
    special_instructions     TEXT,
    notes                    TEXT,
    created_at               TIMESTAMP,
    updated_at               TIMESTAMP,
    CONSTRAINT fk_shipping_order
        FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_shipping_address
        FOREIGN KEY (shipping_address_id) REFERENCES addresses (id) ON DELETE CASCADE
);


-- =====================================================================
-- 14. SHIPPING STATUSES
-- =====================================================================

CREATE TABLE shipping_statuses (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipping_id  BIGINT NOT NULL,
    status       VARCHAR(255) NOT NULL,
    location     VARCHAR(255) NOT NULL,
    timestamp    TIMESTAMP NOT NULL,
    description  TEXT,
    notes        TEXT,
    updated_by   VARCHAR(255),
    created_at   TIMESTAMP,
    CONSTRAINT fk_status_shipping
        FOREIGN KEY (shipping_id) REFERENCES shippings (id) ON DELETE CASCADE
);


-- =====================================================================
-- 15. SUBSCRIBERS
-- =====================================================================

CREATE TABLE subscribers (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(255) NOT NULL,
    email           VARCHAR(255) NOT NULL UNIQUE,
    active          BOOLEAN NOT NULL DEFAULT TRUE,
    subscribed_at   TIMESTAMP,
    unsubscribed_at TIMESTAMP
);


-- =====================================================================
-- 16. FILE METADATA
-- =====================================================================

CREATE TABLE file_metadata (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id           VARCHAR(36) NOT NULL UNIQUE,
    original_file_name  VARCHAR(255) NOT NULL,
    stored_file_name    VARCHAR(255) NOT NULL UNIQUE,
    storage_path        VARCHAR(255) NOT NULL,
    content_type        VARCHAR(255) NOT NULL,
    file_size           BIGINT NOT NULL,
    checksum            VARCHAR(255),
    uploaded_at         TIMESTAMP,
    uploaded_by         VARCHAR(255)
);


-- =====================================================================
-- 17. ASSET LINKS
-- =====================================================================

CREATE TABLE asset_links (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_id        BIGINT NOT NULL,
    owner_type     VARCHAR(50) NOT NULL,
    owner_id       BIGINT NOT NULL,
    purpose        VARCHAR(50) NOT NULL,
    alt_text       VARCHAR(255),
    display_order  INTEGER NOT NULL DEFAULT 0,
    is_primary     BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_assetlink_file
        FOREIGN KEY (file_id) REFERENCES file_metadata (id) ON DELETE CASCADE
);

CREATE INDEX idx_asset_owner ON asset_links (owner_type, owner_id);
CREATE INDEX idx_asset_file  ON asset_links (file_id);


